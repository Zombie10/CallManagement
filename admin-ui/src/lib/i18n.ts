export const CATALOG: Record<AdminLocale, Record<string, string>> = { es, en };

const TOOL_KEYS: Record<string, string> = {
  web_search: "tools.web_search",
  x_search: "tools.x_search",
  file_search: "tools.file_search",
  code_interpreter: "tools.code_interpreter",
};

const SETTING_TOOL_KEYS: Record<string, string> = {
  XAI_ENABLE_WEB_SEARCH: "web_search",
  XAI_ENABLE_X_SEARCH: "x_search",
  XAI_ENABLE_FILE_SEARCH: "file_search",
  XAI_ENABLE_CODE_INTERPRETER: "code_interpreter",
};

export function initialAdminLocale(stored: string | null | undefined): AdminLocale {
  return stored === "en" ? "en" : DEFAULT_ADMIN_LOCALE;
}

export function translate(
  key: string,
  locale: AdminLocale = DEFAULT_ADMIN_LOCALE,
  vars?: Record<string, string | number>,
): string {
  let text = CATALOG[locale][key] ?? CATALOG.es[key] ?? key;
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
  }
  return text;
}

export function toolLabel(id: string, locale: AdminLocale = DEFAULT_ADMIN_LOCALE): string {
  const key = TOOL_KEYS[id];
  if (!key) return id;
  return translate(key, locale);
}

export function presentSettingLabel(
  key: string,
  fallback: string,
  locale: AdminLocale = DEFAULT_ADMIN_LOCALE,
): string {
  const toolId = SETTING_TOOL_KEYS[key];
  if (toolId) return toolLabel(toolId, locale);
  const catalogKey = `settings.field.${key}`;
  return CATALOG[locale][catalogKey] ?? CATALOG.es[catalogKey] ?? fallback;
}

export function settingsSectionLabel(sectionId: string, locale: AdminLocale = DEFAULT_ADMIN_LOCALE): string {
  return translate(`settings.section.${sectionId}`, locale);
}
